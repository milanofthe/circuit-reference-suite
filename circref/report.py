"""Generated documentation: one README per case and library, and the tables in the
top README. Pure functions of the committed data, so ``circref check`` can rebuild
them and fail when the committed copy is stale."""
from __future__ import annotations

import os
import re

from . import classify
from .entry import ROOT, Case, Library, load_library

CASES_BEGIN = "<!-- cases:begin (generated by `python -m circref build`, do not edit) -->"
CASES_END = "<!-- cases:end -->"
LIBRARIES_BEGIN = "<!-- libraries:begin (generated by `python -m circref build`, do not edit) -->"
LIBRARIES_END = "<!-- libraries:end -->"
CANDIDATES_BEGIN = "<!-- candidates:begin (generated by `python -m circref build`, do not edit) -->"
CANDIDATES_END = "<!-- candidates:end -->"
FOOTER = "Generated by `python -m circref build`. Do not edit by hand."


def _source_lines(src: dict) -> list[str]:
    url = src["url"] + (f" (commit `{src['commit']}`)" if "commit" in src else "")
    url += f", {src['version']}" if "version" in src else ""
    lines = [f"- Authors: {', '.join(src['authors'])}", f"- URL: {url}"]
    if src.get("root"):
        lines.append(f"- Path: `{src['root']}`")
    if "doi" in src:
        lines.append(f"- DOI: [{src['doi']}](https://doi.org/{src['doi']})")
    lines.append(f"- License: {src['license']}")
    if "citation" in src:
        lines.append(f"- Cite as: {src['citation']}")
    return lines


def _source_link(src: dict) -> str:
    link = f"[{src.get('name', 'source')}]({src['url']})"
    if "doi" in src:
        link += f" [doi](https://doi.org/{src['doi']})"
    return link


def _anchor(heading: str) -> str:
    """GitHub's anchor for a markdown heading."""
    return re.sub(r"[^a-z0-9 _-]", "", heading.lower()).replace(" ", "-")


def status_text(case: Case) -> str:
    label, reasons = case.status()
    return label if label == "complete" else f"{label} ({len(reasons)})"


def _rel(path) -> str:
    return path.relative_to(ROOT).as_posix()


def _link(path, base) -> str:
    """A link from ``base`` to ``path``, both inside the repository."""
    return os.path.relpath(path, base).replace("\\", "/")


def case_readme(case: Case) -> str:
    label, reasons = case.status()
    lines = [f"# {case.title}", "",
             f"{case.family} | {', '.join(sorted({n.dialect for n in case.netlists()}))} | "
             f"status: **{label}**", "", "## Source", ""] + _source_lines(case.source)
    lines += ["", "## Netlists", "",
              "| file | dialect | analyses | devices | size | linear | portability | libraries |",
              "|---|---|---|---|---|---|---|---|"]
    for n in case.netlists():
        g = case.graphs[n.file]
        libs = ", ".join(f"[{lib}]({_link(load_library(lib).directory, case.directory)})"
                         for lib in sorted(g.libraries)) or "-"
        port, why = classify.portability(g)
        port += f" ({', '.join(why)})" if why and port == "specific" else ""
        lines.append(f"| [`{n.file}`]({n.file}) | {n.dialect} | {', '.join(g.analyses)} | "
                     f"{g.devices} | {classify.size(g)} | "
                     f"{'yes' if classify.linear(g) else 'no'} | {port} | {libs} |")
    if any(n.note for n in case.netlists()):
        lines += [""] + [f"- `{n.file}`: {n.note}" for n in case.netlists() if n.note]
    lines += ["", "Devices: instances once the subcircuits defined in this case are expanded; "
              "a device from a library or a compiled model counts once. Size, linear and "
              "portability: see the top README."]
    external: dict[tuple[str, str], set[str]] = {}
    for name, g in case.graphs.items():
        for e in g.edges:
            if case.directory in e.origin.parents and (
                    e.missing or case.directory not in e.target.parents):
                to = (f"[{_rel(e.target)}]({_link(e.target, case.directory)})"
                      if e.target else "missing")
                external.setdefault((e.ref.target, to), set()).add(name)
    if external:
        lines += ["", "## External references", "", "| as written | resolves to | netlists |",
                  "|---|---|---|"]
        lines += [f"| `{t}` | {r} | {len(n)} |" for (t, r), n in sorted(external.items())]
    adapted = case.adapted()
    if adapted:
        lines += ["", "## Files not from upstream", ""]
        lines += [f"- `{f['path']}`: {f['provenance']}, {f['how']}" for f in adapted]
    if "notes" in case.raw:
        lines += ["", "## Notes", "", case.raw["notes"].strip()]
    if label == "incomplete":
        lines += ["", "## Open questions", ""] + [f"- {r}" for r in reasons]
    lines += ["", FOOTER, ""]
    return "\n".join(lines)


def library_readme(lib: Library) -> str:
    lines = [f"# {lib.title}", "", "## Source", ""] + _source_lines(lib.source)
    lines += ["", f"{len(lib.files())} files, "
              f"{sum((lib.directory / f['path']).stat().st_size for f in lib.files()) / 1e6:.1f} MB."]
    if lib.raw.get("subset"):
        lines += ["", f"Subset of upstream: {lib.raw['subset']}"]
    if lib.resolve_table():
        lines += ["", "## External references", "", "| as written | resolves to |", "|---|---|"]
        lines += [f"| `{k}` | `{v or 'missing'}` |" for k, v in lib.resolve_table().items()]
    adapted = lib.adapted()
    if adapted:
        lines += ["", "## Files not from upstream", ""]
        lines += [f"- `{f['path']}`: {f['provenance']}, {f['how']}" for f in adapted]
    if "notes" in lib.raw:
        lines += ["", "## Notes", "", lib.raw["notes"].strip()]
    lines += ["", FOOTER, ""]
    return "\n".join(lines)


def cases_table(cases: list[Case]) -> str:
    rows = [CASES_BEGIN, ""]
    by_source: dict[str, list[Case]] = {}
    for c in cases:
        by_source.setdefault(c.source["name"], []).append(c)
    order = sorted(by_source.items(), key=lambda kv: kv[0].lower())
    rows += ["| source | cases | netlists | dialects | complete | adapted | incomplete | license |",
             "|---|---|---|---|---|---|---|---|"]
    for name, group in order:
        labels = [c.status()[0] for c in group]
        rows.append(f"| [{name}](#{_anchor(name)}) | {len(group)} | "
                    f"{sum(len(c.netlists()) for c in group)} | "
                    f"{', '.join(sorted({n.dialect for c in group for n in c.netlists()}))} | "
                    f"{labels.count('complete')} | {labels.count('adapted')} | "
                    f"{labels.count('incomplete')} | "
                    f"{', '.join(sorted({c.source['license'] for c in group}))} |")
    rows.append(f"| total | {len(cases)} | {sum(len(c.netlists()) for c in cases)} | | | | | |")
    rows.append("")
    rows += _overview(cases)
    for name, group in order:
        src = group[0].source
        n = sum(len(c.netlists()) for c in group)
        licenses = ", ".join(sorted({c.source["license"] for c in group}))
        rows += [f"### {name}", "", f"[{src['url']}]({src['url']}) | {len(group)} cases, "
                 f"{n} netlists | {licenses}", "",
                 "| case | netlists | dialects | analyses | devices | linear | portability | "
                 "libraries | status |", "|---|---|---|---|---|---|---|---|---|"]
        for c in group:
            graphs = list(c.graphs.values())
            analyses = sorted({a for g in graphs for a in g.analyses})
            ports = _tally(classify.portability(g)[0] for g in graphs)
            linear = sum(classify.linear(g) for g in graphs)
            rows.append(f"| [{c.id}](cases/{c.id}) | {len(graphs)} | "
                        f"{', '.join(sorted({n.dialect for n in c.netlists()}))} | "
                        f"{', '.join(analyses)} | {max(g.devices for g in graphs)} | "
                        f"{linear}/{len(graphs)} | {ports} | "
                        f"{', '.join(c.libraries()) or '-'} | {status_text(c)} |")
        rows.append("")
    rows += [CASES_END]
    return "\n".join(rows)


def _tally(labels) -> str:
    counts: dict[str, int] = {}
    for label in labels:
        counts[label] = counts.get(label, 0) + 1
    return ", ".join(f"{k} {v}" if len(counts) > 1 else k for k, v in counts.items())


def _overview(cases: list[Case]) -> list[str]:
    """Netlists by dialect against size, linearity and portability."""
    sizes = [name for name, _ in classify.SIZES]
    ports = ["core", "veriloga", "specific"]
    table: dict[str, dict[str, int]] = {}
    for c in cases:
        for n in c.netlists():
            g = c.graphs[n.file]
            row = table.setdefault(n.dialect, {})
            for key in (classify.size(g), classify.portability(g)[0],
                        "linear" if classify.linear(g) else "nonlinear", "all"):
                row[key] = row.get(key, 0) + 1
    cols = ["all"] + sizes + ["linear", "nonlinear"] + ports
    out = ["Netlists by dialect:", "", "| dialect | " + " | ".join(cols) + " |",
           "|---" * (len(cols) + 1) + "|"]
    for d, row in sorted(table.items(), key=lambda kv: -kv[1]["all"]):
        out.append(f"| {d} | " + " | ".join(str(row.get(k, 0)) for k in cols) + " |")
    total = {k: sum(r.get(k, 0) for r in table.values()) for k in cols}
    out.append("| total | " + " | ".join(str(total[k]) for k in cols) + " |")
    return out + [""]


def libraries_table(libs: list[Library]) -> str:
    rows = [LIBRARIES_BEGIN, "", "| library | content | files | source | license |",
            "|---|---|---|---|---|"]
    for lib in libs:
        rows.append(f"| [{lib.id}](libraries/{lib.id}) | {lib.title} | {len(lib.files())} | "
                    f"{_source_link(lib.source)} | {lib.source['license']} |")
    rows += ["", LIBRARIES_END]
    return "\n".join(rows)


def candidates_table(candidates: list[dict]) -> str:
    rows = [CANDIDATES_BEGIN, "", "| source | license | has | blocked by |", "|---|---|---|---|"]
    for c in candidates:
        rows.append(f"| [{c['name']}]({c['url']}) | {c['license']} | {c['has']} | "
                    f"{c['blocker']}: {c['missing']} |")
    rows += ["", CANDIDATES_END]
    return "\n".join(rows)


def _replace(text: str, begin: str, end: str, body: str) -> str:
    head, rest = text.split(begin, 1)
    return head + body + rest.split(end, 1)[1]


def top_readme(cases: list[Case], libs: list[Library], candidates: list[dict]) -> str:
    text = (ROOT / "README.md").read_text(encoding="utf-8")
    text = _replace(text, CASES_BEGIN, CASES_END, cases_table(cases))
    text = _replace(text, LIBRARIES_BEGIN, LIBRARIES_END, libraries_table(libs))
    return _replace(text, CANDIDATES_BEGIN, CANDIDATES_END, candidates_table(candidates))
